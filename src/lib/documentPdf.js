import { DOCUMENT_LABELS, DOCUMENT_OWNERS, documentFileName } from '../data/documents.js'
import { NOW, TZ } from '../data/now.js'
import { documentRecipient } from './documents.js'
import { routeSentence } from './route.js'

/*
  A one-page PDF written by hand: no library, Helvetica only, Latin-1 text,
  A4. Enough for any viewer to open it, so a customer who clicks Download
  holds a real file. The content is synthetic and the footer says so.
*/

const PAGE = { width: 595, height: 842, margin: 56 }

const dateTime = new Intl.DateTimeFormat('en-GB', {
  day: 'numeric',
  month: 'short',
  year: 'numeric',
  hour: '2-digit',
  minute: '2-digit',
  hourCycle: 'h23',
  timeZone: TZ,
})

// A PDF string literal: the three special characters are escaped, and
// anything WinAnsi cannot show becomes "?" rather than corrupting the file.
const pdfString = (text) =>
  `(${text.replace(/[^\x20-\xff]/g, '?').replace(/[\\()]/g, (char) => `\\${char}`)})`

// Everything written is ASCII or Latin-1, so one character is one byte and
// the cross-reference offsets can be counted on string length.
const byteLength = (text) => text.length

// Lines are laid out top to bottom; `y` pins one (the footer) instead.
function contentStream(lines) {
  let y = PAGE.height - PAGE.margin
  return lines
    .map(({ text, size = 11, bold = false, gap = 0, y: fixed = null }) => {
      if (fixed === null) y -= size * 1.5 + gap
      const font = bold ? 'F2' : 'F1'
      return `BT /${font} ${size} Tf ${PAGE.margin} ${fixed ?? y} Td ${pdfString(text)} Tj ET`
    })
    .join('\n')
}

export function buildPdf(lines) {
  const content = contentStream(lines)
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE.width} ${PAGE.height}] ` +
      '/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
    `<< /Length ${byteLength(content)} >>\nstream\n${content}\nendstream`,
  ]

  let out = '%PDF-1.4\n'
  const offsets = []
  objects.forEach((body, index) => {
    offsets.push(byteLength(out))
    out += `${index + 1} 0 obj\n${body}\nendobj\n`
  })
  const xref = byteLength(out)
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  for (const offset of offsets) out += `${String(offset).padStart(10, '0')} 00000 n \n`
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`

  return new Blob([Uint8Array.from(out, (char) => char.charCodeAt(0))], { type: 'application/pdf' })
}

// Who issued a document, from its owner: the shipper is our origin site, the
// others are the carrier or customs party on the route.
function issuerOf(view, type) {
  const owner = DOCUMENT_OWNERS[type]
  if (owner === 'shipper') return `${view.origin.label} (shipper)`
  return `${documentRecipient(view, type).name} (${owner === 'carrier' ? 'carrier' : 'customs broker'})`
}

// The downloadable version of one document on a shipment.
export function documentPdf(view, doc) {
  const issued = doc.sentAt ?? NOW
  return buildPdf([
    { text: `${DOCUMENT_LABELS[doc.type]}, order ${view.id}`, size: 20, bold: true },
    { text: routeSentence(view), size: 12, gap: 4 },
    { text: `Customer: ${view.customerName}`, gap: 18 },
    { text: `Issued by: ${issuerOf(view, doc.type)}` },
    { text: `Date: ${dateTime.format(new Date(issued))}` },
    { text: `Reference: ${documentFileName(doc.type, view.id)}` },
    { text: 'Prototype document, synthetic data. Generated by Convoy.', size: 9, y: PAGE.margin },
  ])
}
