import { Sparkles } from 'lucide-react'
import { useEffect, useId, useRef, useState } from 'react'
import './AiStamp.css'

const VARIANTS = {
  estimate: 'Convoy estimate',
  suggests: 'Convoy suggests',
  summary: 'Convoy summary',
  drafted: 'Drafted by Convoy',
  interpreted: 'Convoy search',
  convoy: 'Convoy',
}

const POPOVER_WIDTH = 280

// The one marker for simulated output: a tinted chip with a spark, and the
// explanation one click away. Pair it with <Why> on the same card so the
// rationale is never more than a glance away. `dense` drops the icon so a
// stamp in a tight row keeps its size.
export default function AiStamp({ variant = 'estimate', dense = false, className = '' }) {
  const [open, setOpen] = useState(false)
  const [align, setAlign] = useState('left')
  const root = useRef(null)
  const button = useRef(null)
  const popoverId = useId()

  // Outside click or Escape closes it; Escape also puts focus back on the chip
  // and is consumed, so a dialog around the stamp stays open.
  useEffect(() => {
    if (!open) return undefined
    const onPointerDown = (event) => {
      if (!root.current?.contains(event.target)) setOpen(false)
    }
    const onKeyDown = (event) => {
      if (event.key !== 'Escape') return
      event.preventDefault()
      event.stopPropagation()
      setOpen(false)
      button.current?.focus()
    }
    document.addEventListener('pointerdown', onPointerDown)
    document.addEventListener('keydown', onKeyDown, true)
    return () => {
      document.removeEventListener('pointerdown', onPointerDown)
      document.removeEventListener('keydown', onKeyDown, true)
    }
  }, [open])

  // Opens under the chip's left edge unless that would run off the viewport.
  const toggle = () => {
    const rect = button.current?.getBoundingClientRect()
    if (rect) setAlign(rect.left + POPOVER_WIDTH > window.innerWidth ? 'right' : 'left')
    setOpen((value) => !value)
  }

  return (
    <span className={`stamp-wrap ${className}`.trim()} ref={root}>
      <button
        type="button"
        className="stamp"
        ref={button}
        aria-expanded={open}
        aria-controls={popoverId}
        onClick={toggle}
      >
        {!dense && <Sparkles size={12} aria-hidden="true" />}
        {VARIANTS[variant]}
      </button>
      {open && (
        <span className="stamp-popover" id={popoverId} data-align={align} role="note">
          <span className="stamp-popover-title">Generated by Convoy</span>
          Built from the facts listed on this card, never from guesses. In this prototype, deterministic rules stand in
          for the production model.
        </span>
      )}
    </span>
  )
}

// The "why" line under a stamped output: the rule, the inputs or the rationale.
export function Why({ children, label = 'Why' }) {
  return (
    <p className="why">
      <span className="why-label">{label}:</span> {children}
    </p>
  )
}
